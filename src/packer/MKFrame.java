    @SuppressWarnings("ResultOfObjectAllocationIgnored")
    private void GButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GButtonActionPerformed
      int lent =(Integer) nuchara.getValue();
      java.util.List<String> po = new java.util.ArrayList<>();
      if(uplet.isSelected()) po.add("ABCDEFGHIJKLMNOPQRSTUVWXYZ");
      if(lowlet.isSelected()) po.add("abcdefghijklmnopqrstuvwxyz");
      if(numbe.isSelected()) po.add("01234567889");
      if(sym.isSelected()) po.add("!@#$%^&*()-=_+[]{};:,.<>?");
      if (po.isEmpty()){
          JOptionPane.showMessageDialog(this, "Tick at least one checks");
      }
      if(lent < po.size()){
          JOptionPane.showMessageDialog(this, 
          "Lent must at least "+po.size());
      }
      java.security.SecureRandom rand = new java.security.SecureRandom();
      StringBuilder all = new StringBuilder();
      java.util.List<Character> charList;
        charList = new java.util.ArrayList<>();
      for (String pool:po){
          all.append(pool);
          charList.add(pool.charAt(rand.nextInt(pool.length())));
      }
      while (charList.size()<lent){
          charList.add(all.charAt(rand.nextInt(all.length())));
      }
      java.util.Collections.shuffle(charList,rand);
      StringBuilder pass = new StringBuilder();
      for (char c:charList){
        pass.append(c);
        
        if (zal.isSelected()) {
          int mar=1+rand.nextInt(15);
          for (int i =0;i < mar; i++){
              pass.append((char) (0x0300+rand.nextInt(0x70)));
          }
        }
      }
      Genaratedbox.setText(pass.toString());
    }//GEN-LAST:event_GButtonActionPerformed

